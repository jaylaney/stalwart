pub const ORCPT_ADDR_TYPE: &str = "rfc822;";

#[derive(Debug)]
pub struct IngestMessage {
    pub sender_address: String,
    pub sender_authentication: SenderAuthentication,
    pub recipients: Vec<IngestRecipient>,
    pub message_blob: BlobHash,
    pub message_size: u64,
    pub session_id: u64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SenderAuthentication {
    Unauthenticated,
    DmarcPass,
    Submission,
}

impl SenderAuthentication {
    pub fn is_authenticated(&self) -> bool {
        !matches!(self, SenderAuthentication::Unauthenticated)
    }
}

#[derive(Debug)]
pub struct IngestRecipient {
    pub address: String,
    pub orcpt: Option<String>,
    pub spam_percentage: Option<u8>,
}

impl IngestRecipient {
    pub fn orcpt_parameter(&self) -> Option<String> {
        self.orcpt
            .as_deref()
            .map(|orcpt| format!("{ORCPT_ADDR_TYPE}{orcpt}"))
    }

    pub fn is_spam(&self) -> bool {
        self.spam_percentage
            .is_some_and(|percentage| percentage >= 50)
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LocalDeliveryStatus {
    Success,
    TemporaryFailure {
        reason: Cow<'static, str>,
    },
    PermanentFailure {
        code: [u8; 3],
        reason: Cow<'static, str>,
    },
}

pub struct LocalDeliveryResult {
    pub status: Vec<LocalDeliveryStatus>,
    pub autogenerated: Vec<AutogeneratedMessage>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AutogeneratedReturnPath {
    Account,
    Null,
}

pub struct AutogeneratedMessage {
    pub account_address: String,
    pub return_path: AutogeneratedReturnPath,
    pub recipients: Vec<String>,
    pub message: Vec<u8>,
    pub notify: Notify,
    pub source: MessageSource,
    pub exploded: bool,
}

pub trait MailDelivery: Sync + Send {
    fn deliver_message(
        &self,
        message: IngestMessage,
    ) -> impl Future<Output = LocalDeliveryResult> + Send;
}

#[cfg(feature = "test_mode")]
pub mod test_received_at {
    use super::IngestRecipient;
    use std::sync::{Arc, Mutex, MutexGuard, PoisonError};

    struct Pair {
        token: Arc<()>,
        sender: String,
        recipients: [(String, u32); 2],
        timestamp: u64,
        uses: [u32; 2],
        mismatched: bool,
    }

    static ACTIVE: Mutex<Option<Pair>> = Mutex::new(None);

    fn active() -> MutexGuard<'static, Option<Pair>> {
        ACTIVE.lock().unwrap_or_else(PoisonError::into_inner)
    }

    /// Applies only to one ordered test fixture's paired local delivery.
    /// This guard does not hold the mutex while the delivery runs.
    #[must_use = "dropping the guard clears the paired arrival timestamp"]
    pub struct PairedReceivedAtGuard {
        token: Arc<()>,
    }

    impl PairedReceivedAtGuard {
        pub fn new(sender: &str, recipients: [(&str, u32); 2], timestamp: u64) -> Self {
            assert_ne!(recipients[0].0, recipients[1].0);
            assert_ne!(recipients[0].1, recipients[1].1);
            let mut active = active();
            assert!(
                active.is_none(),
                "a paired arrival timestamp is already armed"
            );
            let token = Arc::new(());
            *active = Some(Pair {
                token: token.clone(),
                sender: sender.to_owned(),
                recipients: recipients.map(|(address, id)| (address.to_owned(), id)),
                timestamp,
                uses: [0; 2],
                mismatched: false,
            });
            Self { token }
        }

        pub fn assert_used(&self) {
            let (uses, mismatched) = {
                let active = active();
                let pair = active
                    .as_ref()
                    .filter(|pair| Arc::ptr_eq(&pair.token, &self.token))
                    .expect("the paired arrival guard is active");
                (pair.uses, pair.mismatched)
            };
            assert!(
                !mismatched,
                "paired arrival timestamp recipient scope mismatch"
            );
            assert_eq!(uses, [1, 1], "paired arrival timestamp uses");
        }
    }

    impl Drop for PairedReceivedAtGuard {
        fn drop(&mut self) {
            let mut active = active();
            if active
                .as_ref()
                .is_some_and(|pair| Arc::ptr_eq(&pair.token, &self.token))
            {
                *active = None;
            }
        }
    }

    pub(super) fn delivery_token(sender: &str, recipients: &[IngestRecipient]) -> Option<Arc<()>> {
        let mut active = active();
        let Some(pair) = active.as_mut().filter(|pair| pair.sender == sender) else {
            return None;
        };
        let matches = pair.recipients.each_ref().map(|(address, _)| {
            recipients
                .iter()
                .filter(|rcpt| rcpt.address == *address)
                .count()
        });
        if matches == [0, 0] {
            return None;
        }
        if recipients.len() == 2 && matches == [1, 1] {
            Some(pair.token.clone())
        } else {
            pair.mismatched = true;
            None
        }
    }

    pub(super) fn received_at(token: &Arc<()>, address: &str, account_id: u32) -> Option<u64> {
        let mut active = active();
        // A delivery resumed after guard teardown cannot use the next
        // transaction's timestamp, even if its envelope matches again.
        let pair = active
            .as_mut()
            .filter(|pair| Arc::ptr_eq(&pair.token, token))?;
        let index = pair
            .recipients
            .iter()
            .position(|(expected, _)| expected == address)?;
        if pair.recipients[index].1 != account_id {
            pair.mismatched = true;
            return None;
        }
        pair.uses[index] = pair.uses[index].saturating_add(1);
        Some(pair.timestamp)
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        fn paired_received_at_scope_and_restoration() {
            let recipient = |address: &str| IngestRecipient {
                address: address.to_owned(),
                orcpt: None,
                spam_percentage: None,
            };
            let recipients = [recipient("a@example.test"), recipient("b@example.test")];
            let arm = || {
                PairedReceivedAtGuard::new(
                    "sender@example.test",
                    [("a@example.test", 1), ("b@example.test", 2)],
                    123,
                )
            };
            let guard = arm();
            assert!(delivery_token("other@example.test", &recipients).is_none());
            assert!(
                delivery_token("sender@example.test", &[recipient("other@example.test")]).is_none()
            );
            let token = delivery_token("sender@example.test", &recipients).unwrap();
            assert_eq!(received_at(&token, "a@example.test", 1), Some(123));
            assert_eq!(received_at(&token, "b@example.test", 2), Some(123));
            guard.assert_used();
            drop(guard);
            assert!(delivery_token("sender@example.test", &recipients).is_none());

            let guard = arm();
            assert_eq!(received_at(&token, "a@example.test", 1), None);
            assert!(delivery_token("sender@example.test", &recipients[..1]).is_none());
            let token = delivery_token("sender@example.test", &recipients).unwrap();
            assert_eq!(received_at(&token, "b@example.test", 1), None);
            assert_eq!(received_at(&token, "a@example.test", 1), Some(123));
            assert_eq!(received_at(&token, "a@example.test", 1), Some(123));
            let state = active();
            assert!(state.as_ref().unwrap().mismatched);
            assert_eq!(state.as_ref().unwrap().uses, [2, 0]);
            drop(state);
            drop(guard);

            assert!(
                std::panic::catch_unwind(|| {
                    let _guard = arm();
                    panic!("exercise the paired guard's unwind cleanup");
                })
                .is_err()
            );
            assert!(active().is_none());
        }
    }
}

impl MailDelivery for Server {
    async fn deliver_message(&self, message: IngestMessage) -> LocalDeliveryResult {
        #[cfg(feature = "test_mode")]
        let paired_received_at =
            test_received_at::delivery_token(&message.sender_address, &message.recipients);
        // Read message
        let raw_message = match self
            .get_blob(message.message_blob.as_slice(), 0..usize::MAX)
            .await
        {
            Ok(Some(raw_message)) => raw_message,
            Ok(None) => {
                trc::event!(
                    MessageIngest(trc::MessageIngestEvent::Error),
                    Reason = "Blob not found.",
                    SpanId = message.session_id,
                    CausedBy = trc::location!()
                );

                return LocalDeliveryResult {
                    status: (0..message.recipients.len())
                        .map(|_| LocalDeliveryStatus::TemporaryFailure {
                            reason: "Blob not found.".into(),
                        })
                        .collect::<Vec<_>>(),
                    autogenerated: vec![],
                };
            }
            Err(err) => {
                trc::error!(
                    err.details("Failed to fetch message blob.")
                        .span_id(message.session_id)
                        .caused_by(trc::location!())
                );

                return LocalDeliveryResult {
                    status: (0..message.recipients.len())
                        .map(|_| LocalDeliveryStatus::TemporaryFailure {
                            reason: "Temporary I/O error.".into(),
                        })
                        .collect::<Vec<_>>(),
                    autogenerated: vec![],
                };
            }
        };

        // Obtain the account IDs for each recipient
        let mut account_ids: AHashMap<u32, usize> =
            AHashMap::with_capacity(message.recipients.len());
        let mut result = LocalDeliveryResult {
            status: Vec::with_capacity(message.recipients.len()),
            autogenerated: Vec::new(),
        };
        let mut harvest_message = false;
        let mut parsed_message = (message.sender_authentication == SenderAuthentication::DmarcPass
            && self.harvest_enabled())
        .then(|| MessageParser::new().parse(&raw_message))
        .flatten();
        let harvest = parsed_message
            .as_ref()
            .is_some_and(|parsed| self.harvest_candidate(parsed));

        for rcpt in message.recipients {
            let account_id = match self.account_id_from_email(&rcpt.address, false).await {
                Ok(Some(account_id)) => account_id,
                Ok(None) => {
                    // Something went wrong
                    result.status.push(LocalDeliveryStatus::PermanentFailure {
                        code: [5, 5, 0],
                        reason: "Mailbox not found.".into(),
                    });
                    continue;
                }
                Err(err) => {
                    trc::error!(
                        err.details("Failed to lookup recipient.")
                            .ctx(trc::Key::To, rcpt.address)
                            .span_id(message.session_id)
                            .caused_by(trc::location!())
                    );
                    result.status.push(LocalDeliveryStatus::TemporaryFailure {
                        reason: "Address lookup failed.".into(),
                    });
                    continue;
                }
            };
            if let Some(status) = account_ids
                .get(&account_id)
                .and_then(|pos| result.status.get(*pos))
            {
                result.status.push(status.clone());
                continue;
            }

            // Obtain access token
            let status = match self.access_token(account_id).await.and_then(|token| {
                token
                    .build()
                    .assert_has_permission(Permission::EmailReceive)
            }) {
                Ok(access_token) => {
                    // Check if there is an active sieve script
                    match self.sieve_script_get_active(account_id).await {
                        Ok(None) => {
                            // Ingest message
                            if parsed_message.is_none() {
                                parsed_message = MessageParser::new().parse(&raw_message);
                            }
                            self.email_ingest(IngestEmail {
                                raw_message: &raw_message,
                                blob_hash: Some(&message.message_blob),
                                message: parsed_message.as_ref(),
                                access_token: &access_token,
                                mailbox_ids: vec![INBOX_ID],
                                keywords: vec![],
                                #[cfg(feature = "test_mode")]
                                received_at: paired_received_at.as_ref().and_then(|token| {
                                    test_received_at::received_at(token, &rcpt.address, account_id)
                                }),
                                #[cfg(not(feature = "test_mode"))]
                                received_at: None,
                                source: IngestSource::Smtp {
                                    deliver_to: &rcpt.address,
                                    envelope_from: &message.sender_address,
                                    sender_authentication: message.sender_authentication,
                                    is_spam: rcpt.is_spam(),
                                },
                                metadata: None,
                                session_id: message.session_id,
                            })
                            .await
                        }
                        Ok(Some(active_script)) => {
                            Box::pin(self.sieve_script_ingest(
                                &access_token,
                                &message.message_blob,
                                &raw_message,
                                &message.sender_address,
                                message.sender_authentication,
                                &rcpt,
                                message.session_id,
                                active_script,
                                &mut result.autogenerated,
                            ))
                            .await
                        }
                        Err(err) => Err(err),
                    }
                }

                Err(err) => Err(err),
            };

            if !harvest_message && harvest && !rcpt.is_spam() {
                harvest_message = za_harvest_allowed(self, account_id, &status).await;
            }

            let status = match status {
                Ok(ingested_message) => {
                    // Notify state change
                    if ingested_message.change_id != u64::MAX {
                        self.broadcast_push_notification(PushNotification::EmailPush(EmailPush {
                            account_id,
                            email_id: ingested_message.document_id,
                            change_id: ingested_message.change_id,
                        }))
                        .await;
                    }

                    LocalDeliveryStatus::Success
                }
                Err(err) => {
                    let status = match err.as_ref() {
                        trc::EventType::Limit(trc::LimitEvent::Quota) => {
                            LocalDeliveryStatus::TemporaryFailure {
                                reason: "Mailbox over quota.".into(),
                            }
                        }
                        // SPDX-SnippetBegin
                        // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
                        // SPDX-License-Identifier: LicenseRef-SEL
                        #[cfg(feature = "enterprise")]
                        trc::EventType::Limit(trc::LimitEvent::TenantQuota) => {
                            LocalDeliveryStatus::TemporaryFailure {
                                reason: "Organization over quota.".into(),
                            }
                        }
                        // SPDX-SnippetEnd
                        trc::EventType::Security(trc::SecurityEvent::Unauthorized) => {
                            LocalDeliveryStatus::PermanentFailure {
                                code: [5, 5, 0],
                                reason: "This account is not authorized to receive email.".into(),
                            }
                        }
                        trc::EventType::MessageIngest(trc::MessageIngestEvent::Error) => {
                            LocalDeliveryStatus::PermanentFailure {
                                code: err
                                    .value(trc::Key::Code)
                                    .and_then(|v| v.to_uint())
                                    .map(|n| {
                                        [(n / 100) as u8, ((n % 100) / 10) as u8, (n % 10) as u8]
                                    })
                                    .unwrap_or([5, 5, 0]),
                                reason: err
                                    .value_as_str(trc::Key::Reason)
                                    .unwrap_or_default()
                                    .to_string()
                                    .into(),
                            }
                        }
                        _ => LocalDeliveryStatus::TemporaryFailure {
                            reason: "Transient server failure.".into(),
                        },
                    };

                    trc::error!(
                        err.ctx(trc::Key::To, rcpt.address)
                            .span_id(message.session_id)
                    );

                    status
                }
            };

            // Cache response for UID to avoid duplicate deliveries
            account_ids.insert(account_id, result.status.len());

            result.status.push(status);
        }

        drop(parsed_message);
        if harvest_message {
            self.spawn_harvest(raw_message, message.session_id);
        }

        result
    }
}
